func T(lang, key string) string {
	if dict, ok := dictionary[lang]; ok {
		if val, ok := dict[key]; ok {
			return val
		}
	}
	// Fallback to zh_CN
	if dict, ok := dictionary["zh_CN"]; ok {
		if val, ok := dict[key]; ok {
			return val
		}
	}
	return key
}
