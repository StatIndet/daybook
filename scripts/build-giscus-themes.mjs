import * as esbuild from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

// The iframe cannot inherit Daybook's CSS variables or fonts. Resolve its four
// appearances from the same tokens and font faces used by the parent document.
export async function buildGiscusThemes(root) {
  const cssRoot = path.join(root, 'internal', 'embedded', 'static', 'css');
  const [tokens, fonts, shared] = await Promise.all([
    readFile(path.join(cssRoot, 'tokens.css'), 'utf8'),
    readFile(path.join(cssRoot, 'fonts.css'), 'utf8'),
    readFile(path.join(cssRoot, 'components', 'giscus-theme.css'), 'utf8'),
  ]);

  const tokenRules = new Map([...tokens.matchAll(/(:root[^{}]*)\{([^{}]*)\}/g)].map(match => [
    match[1].trim(),
    new Map([...match[2].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(declaration => [declaration[1], declaration[2].trim()])),
  ]));
  const requiredRule = selector => {
    const declarations = tokenRules.get(selector);
    if (!declarations) throw new Error(`Missing Daybook token rule: ${selector}`);
    return declarations;
  };

  // Copy only variables used by the iframe, including dependencies of aliases.
  const referenced = new Set([...shared.matchAll(/var\((--[\w-]+)/g)].map(match => match[1]));
  const fontFaces = [...fonts.matchAll(/@font-face\s*\{[^{}]*\}/g)]
    .map(match => match[0])
    .filter(face => /font-family:\s*"Cormorant Garamond";/.test(face))
    .join('\n')
    .replace(/url\("\/vendor\//g, 'url("../../vendor/');
  if (!fontFaces) throw new Error('Missing Daybook Cormorant Garamond font faces');

  // Keep CJK unicode-range shards shared instead of duplicating their font-face
  // declarations in all four themes. Go fingerprints imports and relative URLs.
  const fontImports = [
    'lxgw-wenkai-screen/regular/result.css',
    'maple-mono-cn/regular/result.css',
    'maple-mono-cn/italic/result.css',
  ].map(file => `@import url("../../vendor/fonts/${file}");`).join('\n');
  const english = requiredRule(':root:lang(en)');
  const englishRule = `:root:lang(en){${[...english].map(([name, value]) => `${name}:${value};`).join('')}}`;

  for (const palette of ['default', 'warm']) {
    for (const theme of ['light', 'dark']) {
      const resolved = new Map(requiredRule(':root'));
      if (theme === 'dark') {
        for (const [name, value] of requiredRule(':root[data-theme="dark"]')) resolved.set(name, value);
      }
      if (palette === 'warm') {
        for (const [name, value] of requiredRule(':root[data-palette="warm"]')) resolved.set(name, value);
        if (theme === 'dark') {
          for (const [name, value] of requiredRule(':root[data-palette="warm"][data-theme="dark"]')) resolved.set(name, value);
        }
      }

      const selected = new Set(referenced);
      for (const name of selected) {
        const value = resolved.get(name);
        // Shared giscus aliases are defined in the shared stylesheet itself.
        if (!value) {
          if (!new RegExp(`${name}\\s*:`).test(shared)) throw new Error(`Missing Daybook token: ${name}`);
          selected.delete(name);
          continue;
        }
        for (const match of value.matchAll(/var\((--[\w-]+)/g)) selected.add(match[1]);
      }
      const declarations = [...resolved]
        .filter(([name]) => selected.has(name))
        .map(([name, value]) => `${name}:${value};`).join('');
      const source = `${fontImports}\n${fontFaces}\n:root{${declarations}color-scheme:${theme};}\n${englishRule}\n${shared}`;
      // Transform without bundling so imports stay relative to this stylesheet.
      const result = await esbuild.transform(source, { loader: 'css', minify: true });
      const file = path.join(cssRoot, 'components', `giscus-${palette}-${theme}.css`);
      await writeFile(file, `/* Generated by scripts/build-giscus-themes.mjs; edit tokens.css, fonts.css or giscus-theme.css. */\n${result.code}`);
    }
  }
}
