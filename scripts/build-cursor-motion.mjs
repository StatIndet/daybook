import { writeFile, mkdir } from 'node:fs/promises';
import { cursorPath } from '../assets/motion/liquid-loop.mjs';

// Keep the original 118 × 30ms cadence. Simplify sampled outlines to a
// subpixel tolerance at the cursor's 0.2× display scale.
function simplify(points, tolerance = 0.5) {
  if (points.length < 3) return points;
  const first = points[0], last = points.at(-1);
  const dx = last[0] - first[0], dy = last[1] - first[1];
  let farthest = tolerance * tolerance, split = -1;
  for (let i = 1; i < points.length - 1; i++) {
    const p = points[i];
    const t = dx || dy ? Math.max(0, Math.min(1, ((p[0] - first[0]) * dx + (p[1] - first[1]) * dy) / (dx * dx + dy * dy))) : 0;
    const distance = (p[0] - first[0] - t * dx) ** 2 + (p[1] - first[1] - t * dy) ** 2;
    if (distance > farthest) { farthest = distance; split = i; }
  }
  if (split < 0) return [first, last];
  return [...simplify(points.slice(0, split + 1), tolerance).slice(0, -1), ...simplify(points.slice(split), tolerance)];
}

const frames = Array.from({ length: 118 }, (_, frame) => cursorPath(frame).replace(/M[^Z]+Z/g, outline => {
  if (outline.includes('A')) return outline;
  const points = [...outline.matchAll(/[ML](-?[\d.]+),(-?[\d.]+)/g)].map(match => [+match[1], +match[2]]);
  return simplify(points).map((point, index) => `${index ? 'L' : 'M'}${point.join(',')}`).join('') + 'Z';
}));
const directory = new URL('../assets/ts/generated/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL('liquid-loop-frames.ts', directory),
  '// Generated by scripts/build-cursor-motion.mjs from assets/motion/liquid-loop.mjs.\n' +
  'export const liquidLoopFrames: readonly string[] = ' + JSON.stringify(frames) + ';\n');
